// One of the 102 countries in _re/gamedata_json/a16_countries-enc.json
// (BinaryFormatter dump; keys are the C# backing fields "<Name>k__BackingField").
struct Country {
  std::string name;
  std::string continent;
  std::string code;
  std::string currency;
  std::string language;
  std::string demonym;
  std::vector<std::string> cities;
  // DataCountry.GetRetirementAgeForGender @ the two columns of
  // gamedata_json/a16_countries-enc.json (REPORT.en.md 137). They run from 50 to
  // 67, which is why one retirement age for the whole port was wrong.
  int retirementAgeMale = 65;
  int retirementAgeFemale = 65;
  // <FreeCollege>k__BackingField. The tuition screen's free lane only exists for a
  // country that has one (REPORT.en.md 317); 28 of the 102 rows say true.
  bool freeCollege = false;
  // <Adjectival>k__BackingField, used by the free lane's own line.
  std::string adjectival;
};

// One resolved age-up event, taken from a real table row.
struct AgeUp {
  std::string table;      // the real table the row came from
  std::string row_id;     // row number in that table (1-based, data rows)
  std::string title;      // 'Title' / '' for narrative-only tables
  std::string body;       // 'Body' or the narrative string, placeholders resolved
  std::string cta;        // 'CTA'
  std::string choice;     // 'Choice N'
  std::string narrative;  // 'Narrative N'
  // The family lifecycle lines of that same year, written to the log before the
  // scenario's own line ("My mother has been promoted to Tour Operator.").
  std::vector<std::string> extra;
  // A token that survived resolution, with the table it came from (REPORT 207). The card
  // has already fired, so the leak is recorded rather than hidden: the residue test
  // asserts this is empty for every family's spec, and names the table when it is not.
  std::vector<std::string> residue;
  int karma = 0;          // 'Karma Impact N'
  int discipline = 0;     // 'Discipline Impact N'
  int happiness = 0;      // 'Happiness Impact N'
  int health = 0;         // 'Health Impact N' (the fourth stat float, hero+0x8c)
  int smarts = 0;         // 'Intelligence Impact N'
  int looks = 0;          // 'Appearance Impact N'
  // Fame is a float on the hero but the cards move it in whole points; the runner
  // applies and clamps it like the other stats (REPORT.en.md 228).
  int fame = 0;
  // The health the hero's own ailments cost this year (REPORT.en.md 247). It is part
  // of the year's deltas and also named separately, so a test that isolates one
  // card's math can subtract it instead of calling the card wrong.
  int ailmentCost = 0;
  // The card's buttons, when the row has more than one (REPORT.en.md 233). The engine
  // still picks one lane for the script; the play driver needs the labels to show a
  // real menu, and probing for them changed the RNG stream (which is why play had
  // stopped offering any).
  std::vector<std::string> options;
};

