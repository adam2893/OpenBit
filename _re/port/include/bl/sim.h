// The hero's own children (REPORT.en.md 146). The game keeps a SimChild array on the
// life with its own state -- ChildType, MovedOut, Spouse, ExSpouseArray,
// GrandchildArray, RelationshipStatus, ChildSupport, Twins and a dozen
// HeroAgeAtLastAsked* stamps. The port starts with what the three child-dependent
// cards read: who the child is, how old, who the other parent is, whether it lives
// with the hero, and how often the hero has been asked for a paternity test.
struct Child {
  std::string name;        // first name
  std::string lastName;
  bool female = false;
  int age = 0;
  bool alive = true;
  bool movedOut = false;   // SimChild.MovedOut
  // Where this child lives (REPORT.en.md 163), for the same reason ExLover has one:
  // SimChild.IsLivingWithHero and the ex cards' place checks need a place to compare.
  std::string city;
  std::string otherParent; // the partner who is not the hero, when there is one
  bool withCurrentLover = false;  // SimChild.IsChildWithCurrentLover
  int paternityAsked = 0;  // SimChild.NumTimesHeroAskedToTakePaternityTest
  // The hero's age when this child was born. A child cannot be older than the parent,
  // and the fixture creates them at birth, so the array needs to know when each one
  // starts (REPORT.en.md 149).
  int bornAtHeroAge = 0;
  // Whether the hero is the child's father (REPORT.en.md 150). The game does not
  // store this: the paternity results card rolls GetRandomNumber(0,1000) and decides
  // there. The port keeps the answer instead, so a fixture child that belongs to the
  // ex stays hers and the roll's outcome is reproducible.
  bool isHeroes = false;
  // SimChild.Twins (+0x1fc): how many siblings a multiple birth produced (REPORT.en.md 340).
  int twins = 0;
};

struct Life {
  Hero hero;
  int year = 0;
  bool alive = true;
  // Life.WasResurrected (+0x470): set when the Time Machine undoes a death (REPORT 310).
  bool wasResurrected = false;
  std::vector<Person> family;
  std::vector<Child> children;
  // Cards the current year still owes the player, oldest first. ageUp drains one
  // per call and does not advance the age while the queue is not empty.
  // A card pushed for later this year (REPORT.en.md 133). It carries a payload since
  // REPORT.en.md 184: a multi-stage card (the custody fight) has to tell the next stage
  // which child and which row it is about, and a bare enum cannot.
  struct PendingCard {
    int kind = 0;
    int a = -1;   // child index, or -1
    int b = -1;   // row index, or -1
    PendingCard() = default;
    // Implicit from the kind, so every existing push still reads the same.
    PendingCard(int k, int inA = -1, int inB = -1) : kind(k), a(inA), b(inB) {}
  };
  std::vector<PendingCard> pendingCards;
  // The friend-advice card's PresentedCountForScenario counter (REPORT.en.md
  // 100): the game shows that card at most twice in one life.
  int advicePresented = 0;
  // The friend-lover card's own PresentedCountForScenario counter (REPORT.en.md
  // 104): its gate reads the count and pushes only at zero, so that card is the
  // family's one-shot.
  int loverPresented = 0;
  // The mischief card's PresentedCountForScenario counter (REPORT.en.md 318):
  // ScenarioCrimeDelinquencyPush paints at most three times in one life.
  int mischiefPresented = 0;
  // The four coworker cards' own PresentedCountForScenario counters (REPORT.en.md
  // 105). Their gates read the count and withhold the card once it has been
  // shown N+1 times, with N = 4 (annoyance), 3 (inappropriate behaviour),
  // 2 (prank) and 2 (rumor).
  int cwAnnoyPresented = 0;
  int cwInappPresented = 0;
  int cwPrankPresented = 0;
  int cwRumorPresented = 0;
  // The friend-rumor outbound card's queued follow-up (REPORT.en.md 107): the
  // inbound card's "Start a rumor about ..." choice hands the friend over and
  // the next age-up renders the friend's answer, because the port models no
  // scenario push. The card is dismiss-only, so the flag clears on the next
  // age-up whether or not the card is shown.
  bool rumorOutPending = false;
  std::string rumorOutFriend;
  bool rumorOutFemale = false;
  // The hero's own half of the unfriend family (REPORT.en.md 111):
  // ScenarioFriendUnfriendOutbound is opened from the Relationships tab and has no
  // yearly push, so the port queues it when the hero ends the friendship in the
  // inbound card and renders it on the next age-up, the rumor card's pattern.
  bool unfriendOutPending = false;
  std::string unfriendOutFriend;
  bool unfriendOutFemale = false;
  // The assault the friend-weapon encounter hands off to (REPORT.en.md 113):
  // ScenarioAttackInbound(friend, weapon) is linked at [self+0x128] by the
  // encounter's shared tail, so the port queues it and renders it on the next
  // age-up, the unfriend pair's pattern. The friend and the weapon the encounter
  // drew travel with it, and there is no coin, because the game has no yearly push.
  bool attackInPending = false;
  std::string attackInFriend;
  bool attackInFemale = false;
  std::string attackInWeapon;
  std::string attackInVerb;
  // The best-friend request's own clock (REPORT.en.md 109): the game tests the
  // hero's age minus the friend's HeroAgeAtLastBestFriendRequest (>= 11) and
  // stamps that field with the hero's age when the card is pushed, so the port
  // keeps the hero's age at the last such request.
  int bestFriendAge = 0;
};

