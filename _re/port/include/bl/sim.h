// One non-hero family member. The yearly lifecycle lines name these people
// ("My little brother, Jimbo, has been diagnosed with mad cow disease."), so
// each one carries the state those lines read: a relation word, a name, an age,
// a current illness and a job. Report section 37.
struct Person {
  std::string relation;  // after "my ": "mother", "father", "big brother", "half sister"
  std::string name;      // first name; empty for parents, which the game never names
  std::string lastName;
  bool female = false;
  int age = 0;
  bool alive = true;
  std::string disease;   // current illness, empty when healthy
  std::string job;       // current job title, empty when none
  std::string company;
  // A sibling is a person the game keeps its own state for (REPORT.en.md 135):
  // SimSibling.MovedOut at +0x1fd, Spouse at +0x210 (generated by
  // PersonGenerator::GenerateSpouseForThirdPerson) and
  // AgeAtCurrentSpouseMarriage at +0x218. Parents carry none of these.
  bool movedOut = false;
  std::string spouse;      // full name of the sibling's husband/wife, "" when single
  int ageAtMarriage = 0;   // the sibling's age when that marriage happened
  // The sibling's own coming out (REPORT.en.md 274): the confession card and the
  // announcement that later rides the move-out line.
  bool outConsidered = false;
  bool out = false;
  std::string sexuality;   // 'gay' or 'bi', drawn when the confession happens
};

